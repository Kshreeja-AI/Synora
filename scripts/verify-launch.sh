#!/usr/bin/env bash
# verify-launch.sh — post-deploy checks for synora-api. Run it ONLY after the founder has deployed.
#
#   bash scripts/verify-launch.sh                       # defaults below
#   BASE_URL=https://other.example bash scripts/verify-launch.sh
#
# Prints HTTP status codes and PASS/FAIL per check. It never prints a response body, a key, or a header value.
# A check that could not run prints NOT RUN, never PASS.
#
# Cost note: check 3 makes ONE real AI call (uses free-tier quota and one of the per-IP daily requests).
# The 429 burst (check 7) sends invalid bodies on purpose, so it spends no AI quota.

BASE_URL="${BASE_URL:-https://synora-api-0frd.onrender.com}"
ORIGIN="${ORIGIN:-https://keshav-kumar-singh.vercel.app}"
ASSISTANT="$BASE_URL/api/public/assistant"
COLD_START_WAIT="${COLD_START_WAIT:-90}"

failures=0
pass() { echo "PASS     $1"; }
fail() { echo "FAIL     $1"; failures=$((failures + 1)); }
notrun() { echo "NOT RUN  $1"; }

status_of() {
  # status_of <curl args...> -> prints the HTTP status code only ("000" on network failure)
  curl -s -o /dev/null -m 60 -w '%{http_code}' "$@" 2>/dev/null || echo 000
}

echo "target: $BASE_URL   origin: $ORIGIN"

# 1. Cold start: Render's free plan sleeps; wait up to COLD_START_WAIT seconds for /health.
waited=0
code=000
while [ "$waited" -le "$COLD_START_WAIT" ]; do
  code=$(status_of "$BASE_URL/health")
  [ "$code" = "200" ] && break
  sleep 5
  waited=$((waited + 5))
done
if [ "$code" = "200" ]; then pass "1. /health -> 200 (after ~${waited}s)"; else fail "1. /health -> $code after ${COLD_START_WAIT}s"; fi

# 2. Readiness
code=$(status_of "$BASE_URL/ready")
if [ "$code" = "200" ]; then pass "2. /ready -> 200"; else fail "2. /ready -> $code (expected 200)"; fi

# 3. Valid question: 200 and the contract keys present (body is checked, never printed)
tmp=$(mktemp)
code=$(curl -s -o "$tmp" -m 90 -w '%{http_code}' -X POST "$ASSISTANT" \
  -H "Origin: $ORIGIN" -H 'Content-Type: application/json' \
  --data '{"question":"What does Keshav study?"}' 2>/dev/null || echo 000)
if [ "$code" = "200" ] && grep -q '"answer"' "$tmp" && grep -q '"label":"AI-generated by Synora"' "$tmp"; then
  pass "3. valid question -> 200 with answer + label"
else
  fail "3. valid question -> $code (expected 200 with answer + label; 503 means no provider/budget)"
fi
rm -f "$tmp"

# 4. Over-long question (501 chars) must be rejected
long=$(head -c 501 /dev/zero | tr '\0' 'x')
code=$(status_of -X POST "$ASSISTANT" -H "Origin: $ORIGIN" -H 'Content-Type: application/json' --data "{\"question\":\"$long\"}")
if [ "$code" = "400" ]; then pass "4. 501-char question -> 400"; else fail "4. 501-char question -> $code (expected 400)"; fi

# 5. Wrong Origin must be blocked (403), without reaching the model
code=$(status_of -X POST "$ASSISTANT" -H 'Origin: https://evil.example' -H 'Content-Type: application/json' --data '{"question":"hi"}')
if [ "$code" = "403" ]; then pass "5. wrong Origin -> 403"; else fail "5. wrong Origin -> $code (expected 403)"; fi

# 6. Preflight from the allowed origin, and no wildcard
hdr=$(curl -s -o /dev/null -D - -m 30 -X OPTIONS "$ASSISTANT" -H "Origin: $ORIGIN" \
  -H 'Access-Control-Request-Method: POST' -H 'Access-Control-Request-Headers: content-type' 2>/dev/null | tr -d '\r')
allow=$(echo "$hdr" | grep -i '^access-control-allow-origin:' | head -1 | cut -d' ' -f2-)
if [ "$allow" = "$ORIGIN" ]; then pass "6. preflight allows exactly the portfolio origin"; else fail "6. preflight allow-origin is not exactly the portfolio origin"; fi

# 7. Rate limit: 15 fast requests with an invalid body (no AI spend). Expect at least one 429.
got429=0
for i in $(seq 1 15); do
  code=$(status_of -X POST "$ASSISTANT" -H "Origin: $ORIGIN" -H 'Content-Type: application/json' --data '{}')
  [ "$code" = "429" ] && got429=1
done
if [ "$got429" = "1" ]; then pass "7. burst of 15 -> saw 429"; else fail "7. burst of 15 -> no 429 seen (limit is 10/min per IP)"; fi

# 8. Logs contain no secrets (needs RENDER_API_KEY in the vault; reads it inside Node, not from args)
if [ -f "$HOME/.config/synora/vault.env" ] && command -v node >/dev/null 2>&1; then
  node "$(dirname "$0")/verify-logs.cjs"
  rc=$?
  if [ "$rc" = "0" ]; then pass "8. recent logs: no secret patterns, no vault values"
  elif [ "$rc" = "3" ]; then notrun "8. recent logs could not be fetched"
  else fail "8. recent logs contain secret-shaped text or a vault value (names above)"; fi
else
  notrun "8. no vault or node available for the log scan"
fi

echo
if [ "$failures" = "0" ]; then echo "RESULT: no failures among the checks that ran (see NOT RUN lines)."; else echo "RESULT: $failures check(s) FAILED."; fi
exit "$failures"
