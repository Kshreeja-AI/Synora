/**
 * Provider-agnostic AI capability contracts.
 *
 * The rest of the application (routes, services) depends only on the types
 * and functions in this module and in `./index.ts` — never on a concrete
 * provider. Adding, removing, or swapping a provider is entirely contained
 * within `./providers/*`; nothing outside this directory should ever import
 * `@anthropic-ai/sdk`, `openai`, `@google/generative-ai`, or
 * `@aws-sdk/client-bedrock-runtime` directly.
 *
 * `AICapability` is deliberately an open-ended union with room already
 * reserved for capabilities beyond Release 1's text/code generation (image,
 * video, audio, speech, embeddings, agents). A provider declares which
 * capabilities it implements via `AIProvider.capabilities`; the resolver
 * (`./resolver.ts`) only ever selects among providers that declare the
 * capability being requested. Adding e.g. image generation later means
 * adding an `ImageGenerationRequest`/`ImageGenerationResult` pair and an
 * `ImageGenerationProvider` interface below, and providers implementing it —
 * it does not require changing `TextGenerationProvider`, the resolver's core
 * selection logic, or any provider that only ever supported text generation.
 */

export type AICapability =
  | 'text-generation'
  | 'code-generation'
  /**
   * Provider-NATIVE tool calling: the model itself chooses a tool and emits
   * structured arguments for it. Declared only by providers whose adapter
   * in `./providers/` actually implements the mapping in both directions —
   * never inferred from the vendor's marketing. Synora's agent runtime has
   * always had orchestration-level tool use (its own planner picking tools);
   * that is a different thing and does not require this capability.
   */
  | 'tool-calling'
  // Reserved for future capabilities — intentionally not implemented in
  // Release 1, but the type is listed here so provider descriptors and the
  // resolver's capability-filtering logic never need to change shape when
  // these are added, only extended.
  | 'image-generation'
  | 'video-generation'
  | 'audio-generation'
  | 'speech-to-text'
  | 'text-to-speech'
  | 'embeddings'
  | 'agent';

/**
 * `text-generation` and `code-generation` share one request/response shape:
 * "code" is not a different wire protocol, it is a different `mode` that
 * providers may use to select a more code-specialized model or system
 * prompt. This matches how every provider in scope actually works — none of
 * them expose a distinct "code" endpoint separate from chat/text completion.
 */
export type TextGenerationMode = 'text' | 'code';

/**
 * A prior conversation turn. `'system'` is accepted here for callers that
 * build history generically, but every provider treats it as equivalent to
 * `systemPrompt` (merged into the provider's dedicated system-prompt
 * mechanism) rather than as a turn in the user/assistant exchange — no
 * provider's wire format allows more than one system instruction.
 */
export type ConversationRole = 'user' | 'assistant' | 'system';

/**
 * A tool offered to the model. `inputSchema` is a JSON Schema object
 * describing the tool's arguments — the one format every provider in scope
 * accepts (Anthropic calls it `input_schema`, OpenAI calls it `parameters`;
 * the adapters rename it, Synora does not maintain two schemas).
 */
export interface AIToolDefinition {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
}

/**
 * The model asking to run a tool. `id` is assigned by the provider and MUST
 * be echoed back on the matching `AIToolResult` — it is how the provider
 * pairs a result with the call it answers, so it is carried verbatim and
 * never regenerated by Synora.
 */
export interface AIToolCall {
  id: string;
  name: string;
  input: Record<string, unknown>;
}

/**
 * What running the tool produced, sent back on the next turn. `content` is
 * already-serialized text because that is what every provider's wire format
 * accepts; deciding how a tool's output becomes text belongs to the caller
 * that ran the tool, not to a provider adapter.
 */
export interface AIToolResult {
  toolCallId: string;
  content: string;
  /** True when the tool failed. Providers surface this to the model so it can adapt. */
  isError?: boolean;
}

export interface ConversationMessage {
  role: ConversationRole;
  content: string;
  /**
   * On an `assistant` turn: the tool calls the model made on that turn.
   * Replaying them is mandatory — a provider rejects a tool result that
   * answers a call missing from the history it was given.
   */
  toolCalls?: readonly AIToolCall[];
  /**
   * On a `user` turn: results for tool calls made in the PREVIOUS assistant
   * turn. Kept on the user role because that is the turn direction every
   * provider uses for tool results, even though a human wrote none of it.
   */
  toolResults?: readonly AIToolResult[];
}

/**
 * Whether the model may call a tool this turn. `required` means it must call
 * one; `none` means it must answer in prose. Provider-agnostic names — each
 * adapter maps them to its vendor's spelling.
 */
export type ToolChoice = 'auto' | 'required' | 'none';

export interface TextGenerationRequest {
  /**
   * The newest user turn. Required, even when `messages` is set — with one
   * deliberate exception: a **tool-result continuation** passes `''`, because
   * the caller has tool output to send back and no new human input. An empty
   * prompt appends no final user turn; a non-empty one behaves exactly as it
   * always has, so no existing caller changes.
   */
  prompt: string;
  /**
   * Prior turns, oldest first, NOT including `prompt` itself. Omit for a
   * single-shot completion — every Release 1/2 caller does this today, and
   * every provider's behavior is unchanged when this is absent. A
   * conversational caller (e.g. Release 3's message service) passes the
   * windowed message history here; providers append `prompt` as the final
   * user turn before calling their SDK.
   */
  messages?: readonly ConversationMessage[];
  mode?: TextGenerationMode;
  systemPrompt?: string;
  maxTokens?: number;
  temperature?: number;
  /** Override the provider's configured default model for this one call. */
  model?: string;
  /**
   * Tools the model may call this turn. Omit for a plain completion — every
   * existing caller does, and every provider's behavior is unchanged when
   * this is absent. Sending tools to a provider that does not declare
   * `tool-calling` is a caller error, not a silent no-op: those adapters
   * ignore the field, which is why `providersForCapability('tool-calling')`
   * exists to check first.
   */
  tools?: readonly AIToolDefinition[];
  /** Ignored unless `tools` is set. Defaults to the provider's own default (`auto`). */
  toolChoice?: ToolChoice;
}

export interface TextGenerationUsage {
  inputTokens?: number;
  outputTokens?: number;
}

export interface TextGenerationResult {
  text: string;
  /** The provider id that actually served this request, e.g. "anthropic". */
  provider: string;
  /** The concrete model name used, e.g. "claude-sonnet-5". */
  model: string;
  usage?: TextGenerationUsage;
  finishReason?: string;
  /**
   * Tools the model wants run, if any. **Absent, never empty-arrayed**, when
   * the model answered in prose — so `if (result.toolCalls)` is an honest
   * test for "the model wants something run" rather than a length check that
   * treats "no tools offered" and "tools offered, none chosen" alike.
   *
   * `text` may be non-empty alongside these: models routinely explain what
   * they are about to do in the same turn.
   */
  toolCalls?: readonly AIToolCall[];
}

/** Implemented by any provider that can serve text/code generation. */
export interface TextGenerationProvider {
  readonly id: string;
  readonly capabilities: readonly AICapability[];
  generateText(request: TextGenerationRequest): Promise<TextGenerationResult>;
}

/**
 * Image generation. A separate provider interface from text (as the module
 * header describes) — the wire shape and result are entirely different, so
 * forcing it through `generateText` would be dishonest. Providers return raw
 * image bytes (base64) rather than a provider-hosted URL: those URLs expire,
 * and Synora stores the bytes in its own object storage so the returned URL
 * is durable and workspace-controlled.
 */
export interface ImageGenerationRequest {
  prompt: string;
  /** `${width}x${height}`, e.g. "1024x1024". Providers validate supported sizes. */
  size?: string;
  /** How many images to generate. Defaults to 1. */
  count?: number;
  /** Override the provider's configured default model for this one call. */
  model?: string;
}

export interface GeneratedImageData {
  /** Raw image bytes, base64-encoded. */
  base64: string;
  mimeType: string;
  width: number;
  height: number;
}

export interface ImageGenerationResult {
  images: readonly GeneratedImageData[];
  /** The provider id that actually served this request, e.g. "openai". */
  provider: string;
  /** The concrete model used, e.g. "gpt-image-1". */
  model: string;
}

/** Implemented by any provider that can serve image generation. */
export interface ImageGenerationProvider {
  readonly id: string;
  readonly capabilities: readonly AICapability[];
  generateImages(request: ImageGenerationRequest): Promise<ImageGenerationResult>;
}

/**
 * Video generation. Inherently asynchronous — providers take 30 seconds to
 * several minutes to produce a clip — so the interface returns a job handle
 * rather than finished bytes. The service layer polls the provider for
 * completion and stores the result in Synora's own object storage.
 */
export interface VideoGenerationRequest {
  prompt: string;
  /** Duration in seconds. Provider validates supported ranges. */
  duration?: number;
  /** `${width}x${height}`, e.g. "1280x720". */
  size?: string;
  /** Override the provider's configured default model. */
  model?: string;
}

export type VideoJobStatus = 'queued' | 'processing' | 'completed' | 'failed';

export interface VideoJobHandle {
  providerJobId: string;
  provider: string;
  model: string;
}

export interface VideoJobPollResult {
  status: VideoJobStatus;
  /** Set when status is 'completed'. Raw video bytes or a download URL. */
  videoUrl?: string;
  /** Set when status is 'completed'. */
  durationSeconds?: number;
  width?: number;
  height?: number;
  /** Set when status is 'failed'. */
  errorMessage?: string;
}

export interface VideoGenerationProvider {
  readonly id: string;
  readonly capabilities: readonly AICapability[];
  startGeneration(request: VideoGenerationRequest): Promise<VideoJobHandle>;
  pollJob(handle: VideoJobHandle): Promise<VideoJobPollResult>;
  downloadVideo(url: string): Promise<Buffer>;
}

/**
 * Text-to-speech. Synchronous like image generation (a bounded HTTP call,
 * not a long-running job) — providers return raw audio bytes rather than a
 * provider-hosted URL, and Synora stores them in its own object storage.
 */
export interface TextToSpeechRequest {
  /** The text to synthesize. Providers enforce their own length limits. */
  text: string;
  /** Provider-specific voice id/name, e.g. "alloy". */
  voice?: string;
  format?: 'mp3' | 'wav' | 'ogg' | 'flac' | 'aac';
  /** Override the provider's configured default model for this one call. */
  model?: string;
}

export interface TextToSpeechResult {
  /** Raw audio bytes. */
  audio: Buffer;
  mimeType: string;
  /** The provider id that actually served this request, e.g. "openai". */
  provider: string;
  /** The concrete model used, e.g. "tts-1". */
  model: string;
  voice: string;
}

/** Implemented by any provider that can serve text-to-speech. */
export interface TextToSpeechProvider {
  readonly id: string;
  readonly capabilities: readonly AICapability[];
  synthesize(request: TextToSpeechRequest): Promise<TextToSpeechResult>;
}

/**
 * Thrown when a provider call fails for a reason the caller can act on
 * (missing configuration, upstream error, invalid response) — never a raw
 * SDK/HTTP error, so route code never needs to know which provider failed or
 * how that provider's SDK shapes its errors.
 */
export class AIProviderError extends Error {
  constructor(
    message: string,
    readonly providerId: string,
    readonly cause?: unknown
  ) {
    super(message);
    this.name = 'AIProviderError';
  }
}

/**
 * Thrown when Synora's OWN outbound rate limit for a provider is reached —
 * the request was never sent, so this says nothing about the provider's
 * health or the credential's validity. Distinct from a vendor 429 (which
 * arrives as an AIProviderError after a real call): this one is
 * self-imposed pacing, configured via AI_RATE_LIMIT_REQUESTS_PER_SECOND.
 */
export class AIRateLimitedError extends Error {
  constructor(readonly providerId: string) {
    super(
      `Synora's outbound rate limit for provider "${providerId}" was reached, ` +
        'so this request was not sent. It is safe to retry in a moment.'
    );
    this.name = 'AIRateLimitedError';
  }
}

/** Thrown by the resolver when no provider is configured for a capability. */
export class NoProviderConfiguredError extends Error {
  constructor(capability: AICapability, checkedProviders: readonly string[]) {
    super(
      `No AI provider is configured for capability "${capability}". ` +
        `Checked: ${checkedProviders.join(', ')}. ` +
        `Set one of their API key secrets, or set AI_PROVIDER explicitly. ` +
        `See docs/production/R1-e_AI_PROVIDER_ABSTRACTION.md.`
    );
    this.name = 'NoProviderConfiguredError';
  }
}
