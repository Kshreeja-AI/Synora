import { describe, it, expect, beforeEach, vi } from 'vitest';
import express from 'express';
import request from 'supertest';

const ORIGIN = 'https://keshav-kumar-singh.vercel.app';

const mocks = vi.hoisted(() => ({
  instrumentedGenerate: vi.fn(),
  getConfig: vi.fn(),
}));

vi.mock('../../ai/instrumentedGenerate', () => ({
  instrumentedGenerate: mocks.instrumentedGenerate,
}));
vi.mock('../../config', () => ({ getConfig: mocks.getConfig }));

import { createPublicAssistantRouter, PUBLIC_ASSISTANT_SYSTEM_PROMPT } from '../publicAssistant';
import { AIRateLimitedError, NoProviderConfiguredError } from '../../ai';
import { AiBudgetExceededError } from '../../ai/spend-guard';

function makeApp(options?: Parameters<typeof createPublicAssistantRouter>[0]) {
  const app = express();
  app.use('/api/public/assistant', createPublicAssistantRouter(options));
  return app;
}

function withCaps(ai: { globalMaxCostPerDayCents?: number; globalMaxTokensPerDay?: number }) {
  mocks.getConfig.mockReturnValue({ ai });
}

const URL = '/api/public/assistant';

describe('POST /api/public/assistant', () => {
  beforeEach(() => {
    mocks.instrumentedGenerate.mockReset();
    mocks.getConfig.mockReset();
    // Default: a caps-permitting config.
    withCaps({ globalMaxCostPerDayCents: 100, globalMaxTokensPerDay: 50_000 });
    mocks.instrumentedGenerate.mockResolvedValue({
      text: '  Keshav is doing an MBA in Fintech with AI at Invertis University.  ',
      provider: 'p',
      model: 'm',
    });
  });

  describe('valid request', () => {
    it('returns the contract shape and calls the adapter with the published-facts prompt', async () => {
      const res = await request(makeApp())
        .post(URL)
        .set('Origin', ORIGIN)
        .send({ question: 'What does Keshav study?' });

      expect(res.status).toBe(200);
      expect(res.body).toEqual({
        answer: 'Keshav is doing an MBA in Fintech with AI at Invertis University.',
        label: 'AI-generated by Synora',
      });
      expect(res.headers['access-control-allow-origin']).toBe(ORIGIN);

      const [promptId, req] = mocks.instrumentedGenerate.mock.calls[0];
      expect(promptId).toBe('public.assistant');
      expect(req.prompt).toBe('What does Keshav study?');
      expect(req.systemPrompt).toBe(PUBLIC_ASSISTANT_SYSTEM_PROMPT);
    });

    it('caps the answer at 1500 characters', async () => {
      mocks.instrumentedGenerate.mockResolvedValue({ text: 'a'.repeat(5000) });
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(200);
      expect(res.body.answer).toHaveLength(1500);
    });

    it('accepts exactly 500 characters', async () => {
      const res = await request(makeApp()).post(URL).send({ question: 'x'.repeat(500) });
      expect(res.status).toBe(200);
    });
  });

  describe('system prompt', () => {
    it('states the published facts and forbids invention', () => {
      expect(PUBLIC_ASSISTANT_SYSTEM_PROMPT).toContain('MBA in Fintech with AI at Invertis University');
      expect(PUBLIC_ASSISTANT_SYSTEM_PROMPT).toContain('not published');
      expect(PUBLIC_ASSISTANT_SYSTEM_PROMPT).toMatch(/Never invent/);
    });
  });

  describe('bad input', () => {
    it.each([
      ['missing question', {}],
      ['empty question', { question: '' }],
      ['whitespace-only question', { question: '    ' }],
      ['501 characters', { question: 'x'.repeat(501) }],
      ['non-string question', { question: 42 }],
      ['unknown extra field', { question: 'hi', model: 'gpt-x' }],
    ])('rejects %s with 400 and never calls the provider', async (_name, body) => {
      const res = await request(makeApp()).post(URL).send(body);
      expect(res.status).toBe(400);
      expect(res.body).toEqual({ error: 'invalid-request' });
      expect(mocks.instrumentedGenerate).not.toHaveBeenCalled();
    });

    it('rejects malformed JSON with 400', async () => {
      const res = await request(makeApp())
        .post(URL)
        .set('Content-Type', 'application/json')
        .send('{"question": ');
      expect(res.status).toBe(400);
      expect(res.body).toEqual({ error: 'invalid-request' });
    });

    it('rejects a non-JSON body with 400', async () => {
      const res = await request(makeApp())
        .post(URL)
        .set('Content-Type', 'text/plain')
        .send('question=hi');
      expect(res.status).toBe(400);
    });

    it('rejects a body over the 2kb limit with 413', async () => {
      const res = await request(makeApp())
        .post(URL)
        .send({ question: 'hi', padding: 'x'.repeat(4000) });
      expect(res.status).toBe(413);
      expect(res.body).toEqual({ error: 'payload-too-large' });
      expect(mocks.instrumentedGenerate).not.toHaveBeenCalled();
    });
  });

  describe('rate limit', () => {
    it('returns 429 after the per-IP limit within the window', async () => {
      const app = makeApp({ maxRequests: 3, windowMs: 60_000 });
      for (let i = 0; i < 3; i++) {
        await request(app).post(URL).send({ question: 'hi' }).expect(200);
      }
      const res = await request(app).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(429);
      expect(res.body).toEqual({ error: 'rate-limited' });
      expect(mocks.instrumentedGenerate).toHaveBeenCalledTimes(3);
    });

    it('defaults to 10 requests per minute', async () => {
      const app = makeApp();
      for (let i = 0; i < 10; i++) {
        await request(app).post(URL).send({ question: 'hi' }).expect(200);
      }
      await request(app).post(URL).send({ question: 'hi' }).expect(429);
    });
  });

  describe('CORS', () => {
    it('answers the preflight for the portfolio origin only', async () => {
      const res = await request(makeApp())
        .options(URL)
        .set('Origin', ORIGIN)
        .set('Access-Control-Request-Method', 'POST')
        .set('Access-Control-Request-Headers', 'content-type');
      expect(res.status).toBe(204);
      expect(res.headers['access-control-allow-origin']).toBe(ORIGIN);
      expect(res.headers['access-control-allow-credentials']).toBeUndefined();
    });

    it('refuses any other origin with 403, without spending tokens', async () => {
      const res = await request(makeApp())
        .post(URL)
        .set('Origin', 'https://evil.example')
        .send({ question: 'hi' });
      expect(res.status).toBe(403);
      expect(res.body).toEqual({ error: 'origin-not-allowed' });
      expect(res.headers['access-control-allow-origin']).toBeUndefined();
      expect(mocks.instrumentedGenerate).not.toHaveBeenCalled();
    });

    it('refuses a preflight from another origin', async () => {
      const res = await request(makeApp())
        .options(URL)
        .set('Origin', 'https://evil.example')
        .set('Access-Control-Request-Method', 'POST');
      expect(res.status).toBe(403);
    });

    it('never answers with a wildcard origin', async () => {
      const res = await request(makeApp()).post(URL).set('Origin', ORIGIN).send({ question: 'hi' });
      expect(res.headers['access-control-allow-origin']).not.toBe('*');
    });

    it('ignores a wildcard PUBLIC_ASSISTANT_ORIGIN override', async () => {
      process.env.PUBLIC_ASSISTANT_ORIGIN = '*';
      try {
        const res = await request(makeApp())
          .post(URL)
          .set('Origin', 'https://evil.example')
          .send({ question: 'hi' });
        expect(res.status).toBe(403);
      } finally {
        delete process.env.PUBLIC_ASSISTANT_ORIGIN;
      }
    });
  });

  describe('503 not-configured path', () => {
    const expected = { error: 'assistant-not-configured' };

    it('when both global caps are 0', async () => {
      withCaps({ globalMaxCostPerDayCents: 0, globalMaxTokensPerDay: 0 });
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual(expected);
      expect(mocks.instrumentedGenerate).not.toHaveBeenCalled();
    });

    it('when one configured cap is 0', async () => {
      withCaps({ globalMaxCostPerDayCents: 100, globalMaxTokensPerDay: 0 });
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual(expected);
    });

    it('when no cap is configured at all', async () => {
      withCaps({});
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual(expected);
    });

    it('when config is not initialised', async () => {
      mocks.getConfig.mockImplementation(() => {
        throw new Error('config not initialised');
      });
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual(expected);
    });

    it('when no provider is configured', async () => {
      mocks.instrumentedGenerate.mockRejectedValue(
        new NoProviderConfiguredError('text-generation', ['groq', 'openrouter'])
      );
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual(expected);
    });
  });

  describe('other failures', () => {
    it('reports an exhausted budget as 503 with a distinct code', async () => {
      mocks.instrumentedGenerate.mockRejectedValue(
        new AiBudgetExceededError('global', 'daily-tokens', 'cap reached')
      );
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual({ error: 'assistant-budget-exhausted' });
    });

    it('reports provider rate limiting as 503 busy', async () => {
      mocks.instrumentedGenerate.mockRejectedValue(new AIRateLimitedError('groq'));
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(503);
      expect(res.body).toEqual({ error: 'assistant-busy' });
    });

    it('hides provider error details behind a generic 502', async () => {
      mocks.instrumentedGenerate.mockRejectedValue(new Error('upstream exploded with FAKE-CREDENTIAL in message'));
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(502);
      expect(res.body).toEqual({ error: 'assistant-failed' });
      expect(JSON.stringify(res.body)).not.toContain('FAKE-CREDENTIAL');
    });

    it('does not return an empty answer as success', async () => {
      mocks.instrumentedGenerate.mockResolvedValue({ text: '   ' });
      const res = await request(makeApp()).post(URL).send({ question: 'hi' });
      expect(res.status).toBe(502);
    });
  });
});
